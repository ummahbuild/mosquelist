import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const config = JSON.parse(readFileSync('vercel.json', 'utf8'));
const expected = new Map([
  ['/assets/(.*)', 'public, max-age=31536000, immutable'],
  ['/workbox-([a-f0-9]{8}).js', 'public, max-age=31536000, immutable'],
  ['/sw.js', 'public, max-age=0, must-revalidate'],
]);
for (const [source, value] of expected) {
  const rules = config.headers.filter(rule => rule.source === source);
  assert.equal(rules.length, 1, source);
  assert.ok(rules[0].headers.some(header => header.key.toLowerCase() === 'cache-control' && header.value === value), source);
}
for (const rule of config.headers)
  for (const header of rule.headers)
    if (header.key.toLowerCase() === 'cache-control') assert.ok(expected.has(rule.source), 'Review new cache policy explicitly');
assert.ok(!existsSync('public/assets'), 'Do not put mutable public files in the fingerprinted build namespace');

if (process.argv.includes('--build')) {
  function files(dir) {
    return readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)]);
  }
  const assets = files('dist/assets');
  assert.ok(assets.length > 0);
  for (const file of assets)
    assert.match(basename(file), /-[A-Za-z0-9_-]{8}\.[a-z0-9.]+$/, `Non-fingerprinted output cannot receive immutable cache: ${file}`);
  const worker = readFileSync('dist/sw.js', 'utf8');
  const runtimes = [...new Set(worker.match(/workbox-[a-f0-9]{8}/g) ?? [])];
  assert.equal(runtimes.length, 1, 'Review changed Workbox runtime naming');
  assert.ok(existsSync(`dist/${runtimes[0]}.js`));
  // Installation behavior and offline manifests must remain generated by the existing plugin.
  assert.ok(existsSync('dist/site.webmanifest'));
  assert.ok(existsSync('dist/manifest.webmanifest'));
  console.log(JSON.stringify({ immutableBuildAssets: assets.length, immutableRuntime: `${runtimes[0]}.js`, serviceWorkerMustRevalidate: true }));
} else console.log('Static-cache source guard passed; service worker and HTML remain revalidated.');
